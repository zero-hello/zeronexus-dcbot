@dataclass
class CWALocationResult:
    """Resolved location mapping for CWA queries."""
    query: str
    county_name: Optional[str] = None
    station_name: Optional[str] = None
    is_overview: bool = False
    is_matched: bool = False


class CWALocationResolver:
    """Deterministic resolver mapping user queries to CWA counties and stations."""

    OVERVIEW_KEYWORDS = ["台灣", "臺灣", "全台", "全臺灣", "全島", "全省"]

    @classmethod
    def resolve(cls, query: str) -> CWALocationResult:
        """Resolves natural language location string or user prompt to CWA county and station."""
        raw = query.strip()

        # 1. Check for Taiwan overview
        for kw in cls.OVERVIEW_KEYWORDS:
            if kw in raw:
                has_specific = any(c in raw for c in COUNTY_ALIASES if c not in ["台灣", "臺灣"])
                if not has_specific:
                    return CWALocationResult(query=raw, is_overview=True, is_matched=True)

        # 2. Check direct district/town matches (longer tokens first)
        clean_text = raw
        sorted_districts = sorted(DISTRICT_STATION_MAP.keys(), key=len, reverse=True)
        for dist in sorted_districts:
            if dist in clean_text:
                st, cty = DISTRICT_STATION_MAP[dist]
                return CWALocationResult(
                    query=dist,
                    county_name=cty,
                    station_name=st,
                    is_overview=False,
                    is_matched=True,
                )

        # 3. Check county aliases
        sorted_counties = sorted(COUNTY_ALIASES.keys(), key=len, reverse=True)
        for alias in sorted_counties:
            if alias in clean_text:
                cty = COUNTY_ALIASES[alias]
                st = COUNTY_PRIMARY_STATION.get(cty, "臺北")
                return CWALocationResult(
                    query=alias,
                    county_name=cty,
                    station_name=st,
                    is_overview=False,
                    is_matched=True,
                )

        # No match found
        return CWALocationResult(query=raw, is_matched=False)


# Singleton resolver
cwa_location_resolver = CWALocationResolver()
